/**
 * Распознавание намерения по сообщениям клиента.
 * Правила-заглушки, в проде — ML-модель.
 *
 * @param ctx Контекст
 */
export function detectIntent(ctx: IntentContext): Intent {
	const text = ctx.clientText.toLowerCase();
	const rule = RULES.find((r) => r.test(text));

	if (rule) {
		return rule.build(ctx);
	}

	const {name, orderId} = ctx;

	return {
		label:   'уточнение по заказу',
		conf:    70,
		note:    'Точное намерение не распознано — посмотрите карточку клиента.',
		actions: [{id: 'tpl', label: 'Шаблон ответа'}],
		replies: {
			warm: `${name}, добрый день! Уже смотрю ваш вопрос, минуту.`,
			biz:  `Добрый день! Принял обращение в работу, сейчас проверю детали по заказу ${orderId}.`,
			emp:  `${name}, здравствуйте! Спасибо, что написали — разберёмся вместе, сейчас всё проверю.`,
		},
		kb: ['Карточка клиента 360: заказы и прошлые обращения', 'Tone-of-voice гайд поддержки DNS'],
	};
}
