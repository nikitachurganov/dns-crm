const KANC: [RegExp, string][] = [
	[/уважаемый\s+клиент/i, '«Уважаемый клиент»'],
	[/в связи с возникш\w+/i, '«В связи с возникшей ситуацией»'],
	[/просим вас/i, '«Просим вас»'],
	[/оформит[ье] заявлени/i, '«Оформите заявление»'],
	[/в установленной форме/i, '«В установленной форме»'],
	[/довожу до вашего сведения/i, '«Довожу до вашего сведения»'],
	[/в кратчайшие сроки/i, '«В кратчайшие сроки»'],
	[/осуществля\w+/i, '«Осуществляется»'],
	[/вышеуказанн\w+/i, '«Вышеуказанный»'],
	[/данн(ый|ая|ое|ую|ого) (товар|заказ|ситуаци|обращени)/i, '«Данный товар/заказ»'],
	[/незамедлительно/i, '«Незамедлительно»'],
	[/по факту рассмотрения/i, '«По факту рассмотрения»'],
];

/**
 * Канцелярит-детектор
 *
 * @param text Текст сообщения
 * @returns Найденные канцеляризмы
 */
export function checkKanc(text: string): string[] {
	return KANC.filter(([re]) => re.test(text)).map(([, label]) => label);
}
