/** Разбор «🙂 слово слово» в пару символ + ключевые слова */
function parse(line: string): EmojiItem {
	const space = line.indexOf(' ');

	return {char: line.slice(0, space), keywords: line.slice(space + 1).toLowerCase()};
}

export const EMOJI_CATEGORIES: EmojiCategory[] = Object.entries(RAW).map(([id, [title, lines]]) => ({
	id,
	title,
	items: lines.map(parse),
}));

/** Плоский список без повторов, для поиска */
export const ALL_EMOJI: EmojiItem[] = (() => {
	const seen = new Set<string>();

	return EMOJI_CATEGORIES.flatMap(c => c.items).filter(i => !seen.has(i.char) && seen.add(i.char));
})();

/** Поиск по ключевым словам: каждое слово запроса должно входить в описание */
export function searchEmoji(query: string): EmojiItem[] {
	const words = query.toLowerCase().split(/\s+/).filter(Boolean);

	return words.length ? ALL_EMOJI.filter(i => words.every(w => i.keywords.includes(w))) : [];
}
